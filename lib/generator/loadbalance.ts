import type { IspEntry, LoadBalanceConfig } from "../types-loadbalance";
import { args, type ArgValue, raw, ScriptBuilder } from "./script-builder";

/** Penanda pembuat yang ikut di setiap comment agar mudah dikenali di Winbox. */
const BRAND = "By Mikrosetting";

function tag(text?: string): string {
  const clean = (text ?? "").trim();
  return clean ? `${clean} - ${BRAND}` : BRAND;
}

/** Tanggal & jam di header, mis. 17/10/2026 09.42.48. */
function stamp(): string {
  const now = new Date();
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${pad(now.getDate())}/${pad(now.getMonth() + 1)}/${now.getFullYear()} ${pad(now.getHours())}.${pad(now.getMinutes())}.${pad(now.getSeconds())}`;
}

/** Nama pendek RouterOS-safe untuk connection-mark / routing-mark / routing table (huruf besar-kecil dipertahankan, mis. ISP1). */
function ispSlug(isp: IspEntry, index: number): string {
  const clean = isp.name
    .trim()
    .replace(/[^A-Za-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return clean || `ISP${index + 1}`;
}

/**
 * Jatah PCC tiap ISP. Rasio bandwidth: kecepatan dibagi kecepatan terkecil
 * lalu dibulatkan (maks 10 bagian per ISP) supaya jumlah rule mangle tetap
 * wajar. Tanpa rasio, semua ISP mendapat jatah sama.
 */
function ratioWeights(speeds: number[], ratio: boolean): number[] {
  const valid = speeds.every((n) => Number.isFinite(n) && n > 0);
  if (!ratio || !valid || speeds.length === 0) return speeds.map(() => 1);
  const min = Math.min(...speeds);
  return speeds.map((n) => Math.max(1, Math.min(10, Math.round(n / min))));
}

export function generateLoadBalanceScript(config: LoadBalanceConfig): string {
  const s = new ScriptBuilder();
  const v7 = config.ros === "v7";
  const isps = config.isps.filter((i) => i.iface.trim() && i.gateway.trim());
  const lan = config.lanIface.trim();
  const slugs = isps.map((isp, i) => ispSlug(isp, i));
  const addressList = config.localMode === "addresslist";
  const interfaceList = config.localMode === "interfacelist";
  const lanList = config.lanList.trim();
  const localLabel = addressList
    ? "IP Address List (RFC1918)"
    : interfaceList
      ? `In. Interface List (${lanList || "belum diisi"})`
      : `In. Interface (${lan || "belum diisi"})`;
  const weights = ratioWeights(isps.map((isp) => Number(isp.speed)), config.ratioEnabled);
  const totalWeight = weights.reduce((sum, w) => sum + w, 0);
  const { pccEnabled, failoverEnabled, failoverMethod } = config;
  const recursive = failoverEnabled && failoverMethod === "recursive";
  const netwatch = failoverEnabled && failoverMethod === "netwatch";
  const schedule = failoverEnabled && failoverMethod === "schedule";

  /** Pencocok asal trafik lokal pada rule mark-routing: interface LAN, interface-list, atau address-list. */
  const sourceMatch: Array<[string, ArgValue]> = addressList
    ? [["src-address-list", "LOCAL-IP"]]
    : interfaceList
      ? [["in-interface-list", lanList]]
      : [["in-interface", lan]];
  /** Pencocok rule PCC: sama seperti di atas, ditambah tujuan bukan alamat lokal router. */
  const pccMatch: Array<[string, ArgValue]> = [
    ...sourceMatch,
    ...(addressList ? ([["dst-address-list", raw("!LOCAL-IP")]] as Array<[string, ArgValue]>) : []),
    ["dst-address-type", raw("!local")],
  ];

  /** Gateway yang dipakai default route: IP target recursive untuk method recursive, gateway asli untuk netwatch/schedule. */
  const routeGateway = (isp: IspEntry) => (recursive ? isp.checkTarget : isp.gateway);
  /**
   * RouterOS v7 mencari next-hop rekursif di tabel routing yang sama dengan rutenya.
   * Rute di tabel to-ISPx tidak menemukan host-route cek (ada di tabel main), jadi
   * rutenya "unreachable" dan trafik bertanda tidak punya jalan keluar. "@main"
   * memerintahkan pencarian next-hop di tabel main.
   */
  const markedGateway = (isp: IspEntry): ArgValue => (v7 && recursive ? raw(`${isp.checkTarget}@main`) : routeGateway(isp));
  const routeScope: Array<[string, ArgValue]> = recursive
    ? [
        ["check-gateway", "ping"],
        ["scope", 30],
        ["target-scope", 30],
      ]
    : [];
  const markKey = v7 ? "routing-table" : "routing-mark";

  /** Satu blok menu: baris path sekali, lalu satu `add` per entri. */
  let currentMenu = "";
  const menu = (path: string) => {
    s.blank();
    s.line(path);
    currentMenu = path;
  };
  const add = (pairs: Array<[string, ArgValue]>, extra = "") => {
    if (!currentMenu) return;
    s.line(`add ${args(pairs)}${extra}`);
  };

  // ---------------------------------------------------------------- header
  const methodLabel = { recursive: "Recursive Gateway", netwatch: "Netwatch Ping", schedule: "Scheduler Check" }[
    failoverMethod
  ];
  s.comment("MikroTik Load Balancing Connection Classifier (LB PCC)");
  s.comment("Generated by Mikrosetting.com");
  s.comment(`Date: ${stamp()}`);
  s.comment(`RouterOS: ${config.ros ? `${config.ros}.xx` : "(belum dipilih)"}`);
  s.comment(`WAN ISPs: ${isps.length}`);
  s.comment(
    `Recursive Gateway: ${recursive ? "on" : "off"}${failoverEnabled && !recursive ? ` (Failover: ${methodLabel})` : ""}`,
  );
  s.comment(`Bandwidth Ratio: ${config.ratioEnabled ? "on" : "off"}`);
  s.comment(`PCC Type: ${pccEnabled ? config.classifier : "off"}`);
  s.comment(`Local Target: ${localLabel}`);

  if (isps.length < 2) {
    s.blank().comment(
      "Minimal 2 ISP diperlukan agar load balance & failover berjalan — lengkapi dulu section ISP.",
    );
    return s.toString();
  }
  if (!pccEnabled && !failoverEnabled) {
    s.blank().comment(
      "Aktifkan Load Balance (PCC) atau Failover di section Opsi Lanjutan — keduanya mati, tidak ada yang bisa digenerate.",
    );
    return s.toString();
  }
  s.blank();
  s.comment("Syarat: interface tiap ISP dan LAN sudah punya IP address. Backup dulu: /system backup save name=sebelum-loadbalance");

  // ---------------------------------------------------- interface-list LAN
  // Rule mangle yang merujuk interface-list yang belum ada ditolak router, sehingga PCC tidak terpasang sama sekali.
  if (interfaceList && lanList) {
    s.blank();
    s.comment(`Interface-list ${lanList} dibuat bila belum ada. WAJIB diisi interface LAN (bridge/VLAN): /interface list member add list=${lanList} interface=<nama-interface-LAN>`);
    s.line(`:if ([:len [/interface list find where name=${ScriptBuilder.q(lanList)}]] = 0) do={ /interface list add name=${ScriptBuilder.q(lanList)} comment=${ScriptBuilder.q(tag("Interface LAN untuk PCC"))} }`);
  }

  // ------------------------------------------------------------ address-list
  menu("/ip firewall address-list");
  add([["address", "192.168.0.0/16"], ["list", "LOCAL-IP"], ["comment", tag("Local IPs or Private IPs (RFC1918)")]]);
  add([["address", "172.16.0.0/12"], ["list", "LOCAL-IP"]]);
  add([["address", "10.0.0.0/8"], ["list", "LOCAL-IP"]]);

  // --------------------------------------------------------------------- NAT
  if (config.natEnabled) {
    menu("/ip firewall nat");
    isps.forEach((isp, i) => {
      add([
        ["chain", "srcnat"],
        ["out-interface", isp.iface],
        ["dst-address-list", raw("!LOCAL-IP")],
        ["action", "masquerade"],
        ["comment", tag(`Nat Masquerade to ${isp.name || `ISP${i + 1}`}`)],
      ]);
    });
  }

  // ------------------------------------------------------- routing table (v7)
  if (pccEnabled && v7) {
    menu("/routing table");
    slugs.forEach((slug, i) => {
      s.line(`add ${args([["name", `to-${slug}`]])} fib ${args([["comment", tag(`Tabel ${isps[i].name}`)]])}`);
    });
  }

  // ------------------------------------------------------------------- route
  menu("/ip route");
  if (recursive) {
    isps.forEach((isp) => {
      add([
        ["dst-address", isp.checkTarget],
        ["distance", 1],
        ["gateway", isp.gateway],
        ["target-scope", 10],
        ["scope", 10],
        ["comment", tag(`PCC Recursive Check ${isp.name}`)],
      ]);
    });
    s.blank();
  } else if (netwatch) {
    isps.forEach((isp) => {
      add([
        ["dst-address", isp.checkTarget],
        ["distance", 1],
        ["gateway", isp.gateway],
        ["comment", tag(`Pin cek jalur ${isp.name}`)],
      ]);
    });
    s.blank();
  }

  if (pccEnabled) {
    // Satu rute per tabel ISP, menuju gateway ISP itu sendiri.
    isps.forEach((isp, i) => {
      add([
        ...(recursive ? ([["check-gateway", "ping"]] as Array<[string, ArgValue]>) : []),
        ["distance", 1],
        ["gateway", markedGateway(isp)],
        [markKey, `to-${slugs[i]}`],
        ...(recursive
          ? ([
              ["scope", 30],
              ["target-scope", 30],
            ] as Array<[string, ArgValue]>)
          : []),
        ["comment", tag(`PCC Routing Mark to ${isp.name}`)],
      ]);
    });
    // Cadangan: bila ISP pemilik tabel putus, koneksi bertanda tetap bisa keluar lewat ISP lain.
    if (failoverEnabled) {
      isps.forEach((owner, ownerIndex) => {
        isps.forEach((_, k) => {
          if (k === 0) return;
          const entry = isps[(ownerIndex + k) % isps.length];
          add([
            ...routeScope.slice(0, 1),
            ["distance", k + 1],
            ["gateway", markedGateway(entry)],
            [markKey, `to-${slugs[ownerIndex]}`],
            ...routeScope.slice(1),
            ["comment", tag(`PCC Backup Routing Mark ${owner.name} via ${entry.name}`)],
          ]);
        });
      });
    }
  }

  // Default route umum (tanpa mark): trafik router sendiri dan failover utama.
  const defaultRoutes = failoverEnabled ? isps : [isps.reduce((min, isp) => (Number(isp.distance) < Number(min.distance) ? isp : min))];
  defaultRoutes.forEach((isp) => {
    add([
      ...routeScope.slice(0, 1),
      ["distance", isp.distance],
      ["gateway", routeGateway(isp)],
      ...routeScope.slice(1),
      ["comment", tag(`${pccEnabled ? "PCC " : ""}Default Route to ${isp.name}`)],
    ]);
  });

  // ------------------------------------------------------------------ mangle
  if (pccEnabled) {
    menu("/ip firewall mangle");
    add([
      ["action", "accept"],
      ["chain", "prerouting"],
      ["hotspot", raw("from-client,!auth")],
      ["disabled", true],
      ["comment", "HOTSPOT LOGIN BYPASS - Enable this if this Router handles Hotspot Login."],
    ]);
    const bypass: Array<[string, ArgValue]> = [
      ["dst-address-list", "LOCAL-IP"],
      ["src-address-list", "LOCAL-IP"],
    ];
    ["prerouting", "postrouting", "forward", "input", "output"].forEach((chain, i) => {
      add([
        ["action", "accept"],
        ["chain", chain],
        ...bypass,
        ...(i === 0 ? ([["comment", tag("// LOCAL TRAFFIC BYPASS")]] as Array<[string, ArgValue]>) : []),
      ]);
    });

    // Koneksi yang masuk lewat WAN dibalas lewat WAN yang sama.
    isps.forEach((isp, i) => {
      add([
        ["action", "mark-connection"],
        ["chain", "input"],
        ["connection-mark", "no-mark"],
        ["in-interface", isp.iface],
        ["new-connection-mark", `${slugs[i]}-conn`],
        ["passthrough", true],
        ...(i === 0 ? ([["comment", tag("// PCC LOAD BALANCING")]] as Array<[string, ArgValue]>) : []),
      ]);
    });
    isps.forEach((_, i) => {
      add([
        ["action", "mark-routing"],
        ["chain", "output"],
        ["connection-mark", `${slugs[i]}-conn`],
        ["new-routing-mark", `to-${slugs[i]}`],
        ["passthrough", false],
      ]);
    });

    // Pembagian koneksi baru dari jaringan lokal ke tiap ISP.
    let offset = 0;
    isps.forEach((_, i) => {
      for (let r = 0; r < weights[i]; r += 1) {
        add([
          ["action", "mark-connection"],
          ["chain", "prerouting"],
          ["connection-state", "new"],
          ["connection-mark", "no-mark"],
          ["new-connection-mark", `${slugs[i]}-conn`],
          ["passthrough", true],
          ["per-connection-classifier", `${config.classifier}:${totalWeight}/${offset + r}`],
          ...pccMatch,
        ]);
      }
      offset += weights[i];
    });
    isps.forEach((_, i) => {
      add([
        ["action", "mark-routing"],
        ["chain", "prerouting"],
        ["connection-mark", `${slugs[i]}-conn`],
        ["new-routing-mark", `to-${slugs[i]}`],
        ["passthrough", true],
        ...sourceMatch,
      ]);
    });
  }

  // ----------------------------------------------- deteksi failover (non-recursive)
  if (netwatch) {
    menu("/tool netwatch");
    isps.forEach((isp) => {
      const upScript = `:log info "${isp.name} aktif kembali"; /ip route enable [find gateway=${isp.gateway}]`;
      const downScript = `:log info "${isp.name} terputus"; /ip route disable [find gateway=${isp.gateway}]`;
      add([
        ["host", isp.checkTarget],
        ["interval", config.checkInterval],
        ...(v7 ? ([["type", "simple"]] as Array<[string, ArgValue]>) : []),
        ["up-script", upScript],
        ["down-script", downScript],
        ["comment", tag(`Netwatch ${isp.name}`)],
      ]);
    });
  } else if (schedule) {
    const scriptName = "mikrosetting-failover-check";
    const schedulerName = "mikrosetting-failover-scheduler";
    const scriptSource = [
      ":local ok",
      ...isps.flatMap((isp) => [
        `:set ok [/ping ${isp.checkTarget} interface=${isp.iface} count=3]`,
        `:if ($ok > 0) do={ /ip route enable [find gateway=${isp.gateway}] } else={ /ip route disable [find gateway=${isp.gateway}] }`,
      ]),
    ].join("\n");
    menu("/system script");
    add([
      ["name", scriptName],
      ["source", scriptSource],
      ["comment", tag("Cek jalur tiap ISP")],
    ]);
    menu("/system scheduler");
    add([
      ["name", schedulerName],
      ["interval", config.checkInterval],
      ["on-event", scriptName],
      ["comment", tag("Jadwal cek jalur ISP")],
    ]);
  }

  // -------------------------------------------------------------- penutup
  s.blank();
  s.comment("Cek hasil: /ip route print where dst-address=\"0.0.0.0/0\"  |  /ip firewall mangle print stats");
  s.comment("Jika Load Balance tidak berjalan, cek berurutan:");
  s.comment(`1) Interface LAN harus ada di sumber trafik: ${interfaceList ? `interface-list ${lanList || "(belum diisi)"} wajib punya member` : addressList ? "address-list LOCAL-IP" : `interface ${lan || "(belum diisi)"}`}`);
  s.comment("2) /ip firewall mangle print stats  -> counter rule PCC harus naik");
  s.comment(`3) /ip route print where ${v7 ? "routing-table" : "routing-mark"}~"to-"  -> rute tiap ISP harus aktif (huruf A)`);
  s.comment("4) FastTrack bawaan mengabaikan mangle: /ip firewall filter disable [find action=fasttrack-connection]");
  s.comment("5) Tiap ISP harus punya IP + gateway benar dan bisa di-ping: /ping 1.1.1.1 interface=<ether-ISP>");
  s.comment("Hapus semua settingan Load Balance: pakai tab \"Hapus semua\" di sebelah script ini.");
  return s.toString();
}

/**
 * Script penghapus: membuang semua yang dibuat oleh generateLoadBalanceScript.
 * Rule dikenali dari comment penanda DAN dari ciri-cirinya (nama mark, interface,
 * address-list), karena beberapa rule sengaja tidak diberi comment.
 */
export function generateLoadBalanceRemoveScript(config: LoadBalanceConfig): string {
  const s = new ScriptBuilder();
  const v7 = config.ros === "v7";
  const isps = config.isps.filter((i) => i.name.trim() || i.iface.trim());
  const slugs = isps.map((isp, i) => ispSlug(isp, i));
  // Penanda "By Mikrosetting" juga dipakai menu Setup (NAT, anti tethering, dst), jadi
  // rule dikenali dari komentar khas Load Balance saja agar rule menu lain tidak ikut terhapus.
  const lbMangle = `comment~"(PCC LOAD BALANCING|LOCAL TRAFFIC BYPASS) - ${BRAND}"`;
  const lbNat = `comment~"Nat Masquerade to .* - ${BRAND}"`;
  const lbRoute = `comment~"(PCC (Recursive Check|Routing Mark|Backup Routing Mark|Default Route)|Pin cek jalur) .* - ${BRAND}"`;
  const lbNetwatch = `comment~"Netwatch .* - ${BRAND}"`;
  const q = ScriptBuilder.q;

  s.comment("MikroTik Load Balancing - HAPUS SEMUA SETTINGAN");
  s.comment("Generated by Mikrosetting.com");
  s.comment(`Date: ${stamp()}`);
  s.comment(`RouterOS: ${config.ros ? `${config.ros}.xx` : "(belum dipilih)"}`);
  s.comment(`WAN ISPs: ${isps.length}`);
  s.blank();
  s.comment("PERHATIAN");
  s.comment("- Script ini menghapus rule mangle, NAT, route, address-list LOCAL-IP, dan failover");
  s.comment("  yang dibuat oleh script Load Balance dari generator ini.");
  s.comment("- Route default hasil script ikut terhapus. Pastikan router masih punya jalur internet");
  s.comment("  lain (mis. DHCP Client / static route WAN) agar koneksi tidak terputus.");
  s.comment("- Backup dulu: /system backup save name=sebelum-hapus-loadbalance");

  s.blank();
  s.line("/ip firewall mangle");
  s.line(`remove [find where ${lbMangle}]`);
  s.line(`remove [find where comment~"HOTSPOT LOGIN BYPASS"]`);
  s.line("remove [find where action=accept and dst-address-list=LOCAL-IP and src-address-list=LOCAL-IP]");
  for (const slug of slugs) {
    s.line(`remove [find where new-connection-mark=${q(`${slug}-conn`)}]`);
    s.line(`remove [find where new-routing-mark=${q(`to-${slug}`)}]`);
  }

  s.blank();
  s.line("/ip firewall nat");
  s.line(`remove [find where chain=srcnat and ${lbNat} and action=masquerade]`);
  for (const isp of isps.filter((i) => i.iface.trim())) {
    s.line(
      `remove [find where chain=srcnat and out-interface=${q(isp.iface.trim())} and dst-address-list=!LOCAL-IP and action=masquerade]`,
    );
  }

  s.blank();
  s.line("/ip route");
  s.line(`remove [find where ${lbRoute}]`);
  for (const slug of slugs) {
    s.line(`remove [find where ${v7 ? "routing-table" : "routing-mark"}=${q(`to-${slug}`)}]`);
  }

  if (v7) {
    s.blank();
    s.line("/routing table");
    for (const slug of slugs) s.line(`remove [find where name=${q(`to-${slug}`)}]`);
  }

  s.blank();
  s.line("/tool netwatch");
  s.line(`remove [find where ${lbNetwatch}]`);
  s.line("/system scheduler");
  s.line("remove [find where name=mikrosetting-failover-scheduler]");
  s.line("/system script");
  s.line("remove [find where name=mikrosetting-failover-check]");

  s.blank();
  s.line("/ip firewall address-list");
  s.line(
    "remove [find where list=LOCAL-IP and (address=192.168.0.0/16 or address=172.16.0.0/12 or address=10.0.0.0/8)]",
  );

  s.blank();
  s.comment("Selesai. Cek sisa rule: /ip firewall mangle print  |  /ip route print  |  /ip firewall nat print");
  s.comment("Koneksi lama masih tercatat sampai habis sendiri; bila perlu: /ip firewall connection remove [find]");
  return s.toString();
}
